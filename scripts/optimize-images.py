"""Create WebP assets and content-addressed copies for static/CDN hosting.

Requires Pillow with WebP support. Run from any directory with:
    python3 scripts/optimize-images.py
"""
from hashlib import sha256
from pathlib import Path
import json
from PIL import Image, ImageOps

root = Path(__file__).resolve().parents[1]
assets = root / "assets/images/nele"
public = root / "public/images/nele"
public.mkdir(parents=True, exist_ok=True)
manifest = {}
before = after = 0
for original in sorted(assets.glob("*.jpg")):
    image = ImageOps.exif_transpose(Image.open(original)).convert("RGB")
    image.thumbnail((1200, 1200))
    optimized = original.with_suffix(".webp")
    image.save(optimized, "WEBP", quality=78, method=6)
    data = optimized.read_bytes()
    filename = f"{original.stem}.{sha256(data).hexdigest()[:12]}.webp"
    (public / filename).write_bytes(data)
    manifest[original.stem] = f"images/nele/{filename}"
    before += original.stat().st_size
    after += len(data)

source = "// Generated by scripts/optimize-images.py.\n"
source += "export const IMAGE_PATHS = " + json.dumps(manifest, indent=2) + " as const;\n"
(root / "src/data/image-manifest.ts").write_text(source)
print(json.dumps({"images": len(manifest), "beforeBytes": before, "webpBytes": after,
                  "reductionPercent": round((1 - after / before) * 100, 1)}))
